import {
  Box,
  Button,
  CircularProgress,
  Paper,
  Typography,
  IconButton,
  styled,
  useMediaQuery,
  useTheme
} from '@mui/material';
import { ArrowBack as ArrowBackIcon } from '@mui/icons-material';
import { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { useNavigate, useParams } from 'react-router-dom';
import { addDays, endOfMonth, format } from 'date-fns';

import { HorizontalStepper, Calendar } from '../ui';
import { LetItRainFrequency } from './';
import { WizardProfile } from './WizardProfile';
import { useDateFnsLocale } from '../../hooks';
import { CarrotBedComponent } from './CarrotBedComponent';

// Styled components
const WizardContainer = styled(Paper)(({ theme }) => ({
  width: '100%',
  maxWidth: '800px',
  margin: '0 auto',
  padding: 0,
  display: 'flex',
  flexDirection: 'column',
  marginTop: theme.spacing(4),
  [theme.breakpoints.down('md')]: {
    marginTop: 0,
    height: '90vh',
    borderRadius: 0,
    padding: 0,
  }
}));

const WizardHeader = styled(Box)(({ theme }) => ({
  display: 'flex',
  alignItems: 'center',
  marginBottom: theme.spacing(3),
  position: 'relative',
}));

const HeaderTitle = styled(Typography)(() => ({
  flex: 1,
  textAlign: 'center',
  fontWeight: 600,
}));

const WizardContent = styled(Box)(({ theme }) => ({
  flex: 1,
  display: 'flex',
  flexDirection: 'column',
  alignItems: 'center',
  justifyContent: 'space-between',
  maxHeight: '600px',
  overflow: 'auto',
  padding: theme.spacing(2, 0),
}));

const WizardInnerContainer = styled(Box)(() => ({
  display: 'flex',
  flexDirection: 'column',
  alignItems: 'center',
  justifyContent: 'space-between',
}));

const WizardActions = styled(Box)(({ theme }) => ({
  marginTop: theme.spacing(3),
  display: 'flex',
  justifyContent: 'center',
  '& .MuiButton-root': {
    padding: theme.spacing(1.5, 3),
    borderRadius: 0,
  }
}));


// Interface for the component props
interface LetItRainWizardProps {
  onComplete?: (data: WizardData) => void;
  gardenId?: string;
  submitting?: boolean;
  targetMonth: string;
  initialDates?: Date[];
  initialFrequency?: number;
}

// Interface for the wizard data
export interface WizardData {
  frequency: number;
  availableDates: Date[];
  nickname: string;
}

// Step definition interface
interface StepDesc {
  key: string;
  title: string;
  headline: string;
  component: React.ReactNode;
}

export function LetItRainWizard({ onComplete, gardenId, submitting = false, targetMonth, initialDates, initialFrequency }: LetItRainWizardProps) {
  const { t } = useTranslation('letItRain');
  const locale = useDateFnsLocale();
  const theme = useTheme();
  const isMobile = useMediaQuery(theme.breakpoints.down('md'));
  const navigate = useNavigate();
  const { stepNumber } = useParams<{ stepNumber: string }>();

  // State for wizard data
  const [frequency, setFrequency] = useState<number>(initialFrequency ?? 1);
  const [availableDates, setAvailableDates] = useState<Date[]>(initialDates ?? []);
  const [nickname, setNickname] = useState<string>('');
  const [finishAttempted, setFinishAttempted] = useState(false);

  const handleFrequencyChange = (value: number) => {
    setFrequency(value);
  };

  const handleForget = () => {
    setNickname('');
    // Dates and frequency are kept so the new person can reuse or adjust them.
    // WateringWizard reads personId fresh from localStorage on submit, so the
    // new UUID generated by forgetMe() is picked up without a page reload.
  };

  const calendarDates = (() => {
    const [year, month] = targetMonth.split('-').map(Number);
    const start = new Date(year, month - 1, 1);
    const end = endOfMonth(start);
    const dates: Date[] = [];
    let d = new Date(start);
    while (d <= end) {
      dates.push(new Date(d));
      d = addDays(d, 1);
    }
    return dates;
  })();

  // Define the steps
  const steps: StepDesc[] = [
    {
      key: 'frequency',
      title: t('wizard.steps.frequency'),
      headline: t('wizard.headlines.frequency'),
      component: (
        <LetItRainFrequency
          frequency={frequency}
          onChange={(value) => handleFrequencyChange(value)}
        />
      )
    },
    {
      key: 'availability',
      title: t('wizard.steps.availability'),
      headline: t('wizard.headlines.availabilityForMonth', {
        month: format(new Date(targetMonth + '-01'), 'MMMM yyyy', { locale }),
      }),
      component: (
        <Calendar
          dates={calendarDates}
          selectedDates={availableDates}
          onChange={(dates) => setAvailableDates(dates)}
        />
      )
    },
    {
      key: 'profile',
      title: t('wizard.steps.profile'),
      headline: t('wizard.headlines.profile'),
      component: (
        <WizardProfile
          onChange={(name) => { setNickname(name); setFinishAttempted(false); }}
          onForget={handleForget}
          showError={finishAttempted}
        />
      )
    }
  ];

  // Get current step index
  const getCurrentStepIndex = () => {
    if (!stepNumber) return 0;
    const index = parseInt(stepNumber, 10);
    return isNaN(index) || index < 0 || index >= steps.length ? 0 : index;
  };

  const currentStepIndex = getCurrentStepIndex();
  const currentStep = steps[currentStepIndex];

  // Handle navigation
  const handleBack = () => {
    if (currentStepIndex > 0) {
      navigate(`/${gardenId}/watering/wizard/${currentStepIndex - 1}`);
    } else {
      navigate(`/${gardenId}/watering`);
    }
  };

  const handleNext = () => {
    if (currentStepIndex < steps.length - 1) {
      navigate(`/${gardenId}/watering/wizard/${currentStepIndex + 1}`);
    }
  };

  const handleStepClick = (index: number) => {
    navigate(`/${gardenId}/watering/wizard/${index}`);
  };

  const handleFinish = () => {
    if (!nickname.trim()) {
      setFinishAttempted(true);
      return;
    }

    const wizardData: WizardData = {
      frequency,
      availableDates,
      nickname
    };

    if (onComplete) {
      onComplete(wizardData);
      // onComplete handles navigation (async) — don't navigate here
      return;
    }

    navigate(`/${gardenId}/watering`);
  };


  return (
    <WizardContainer elevation={isMobile ? 0 : 3}>
      <WizardInnerContainer>
        <WizardHeader>
          <IconButton
            edge="start"
            color="inherit"
            onClick={handleBack}
            aria-label={t('wizard.buttons.back')}
          >
            <ArrowBackIcon />
          </IconButton>
          <HeaderTitle variant="h5">
            {currentStep.headline}
          </HeaderTitle>
        </WizardHeader>

        <WizardContent>
          <HorizontalStepper
            steps={steps.map(step => step.title)}
            activeStep={currentStepIndex}
            onStepClick={handleStepClick}
          />

          {currentStep.component}
        </WizardContent>

        <WizardActions>
          <Box sx={{ display: 'flex', width: '100%', gap: 2 }}>
            {currentStepIndex > 0 && (
              <Button
                variant="outlined"
                color="primary"
                onClick={handleBack}
                sx={{ flex: 1 }}
              >
                {t('wizard.buttons.back')}
              </Button>
            )}

            {currentStepIndex >= steps.length - 1 ? (
              <Button
                variant="contained"
                color="primary"
                onClick={handleFinish}
                disabled={submitting}
                sx={{ flex: currentStepIndex > 0 ? 2 : 1 }}
                data-cy="wizard-finish"
                startIcon={submitting ? <CircularProgress size={16} color="inherit" /> : undefined}
              >
                {submitting ? t('wizard.submitting') : t('wizard.buttons.finish')}
              </Button>
            ) : (
              <Button
                variant="contained"
                color="primary"
                onClick={handleNext}
                sx={{ flex: currentStepIndex > 0 ? 2 : 1 }}
                data-cy="wizard-next"
              >
                {t('wizard.buttons.next')}
              </Button>
            )}
          </Box>
        </WizardActions>
      </WizardInnerContainer>
      <CarrotBedComponent engagement={frequency} />
    </WizardContainer>
  );
}

export default LetItRainWizard;